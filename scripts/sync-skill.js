#!/usr/bin/env node
// Vendors the analysis engine (src/) and a minimal package.json into the Skill
// directory so that the Skill is self-contained after `npx skills add`, which
// copies only the Skill directory. Use `--check` to verify without writing.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const skillDir = path.join(root, 'skills', 'contextanvil');
const check = process.argv.includes('--check');

function listFiles(dir, base = dir) {
  const out = [];
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, ent.name);
    if (ent.isDirectory()) out.push(...listFiles(abs, base));
    else if (ent.isFile()) out.push(path.relative(base, abs).split(path.sep).join('/'));
  }
  return out.sort();
}

const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const vendoredPackage = `${JSON.stringify({
  name: pkg.name,
  version: pkg.version,
  description: 'Vendored ContextAnvil engine for the ContextAnvil Skill. Generated by scripts/sync-skill.js; do not edit.',
  license: pkg.license,
  type: 'module',
  engines: pkg.engines,
}, null, 2)}\n`;

const expected = new Map([['package.json', Buffer.from(vendoredPackage)]]);
for (const rel of listFiles(path.join(root, 'src'))) {
  expected.set(`src/${rel}`, fs.readFileSync(path.join(root, 'src', ...rel.split('/'))));
}

const problems = [];
const existing = new Set([
  ...(fs.existsSync(path.join(skillDir, 'src')) ? listFiles(path.join(skillDir, 'src')).map((f) => `src/${f}`) : []),
  ...(fs.existsSync(path.join(skillDir, 'package.json')) ? ['package.json'] : []),
]);

for (const [rel, content] of expected) {
  const dest = path.join(skillDir, ...rel.split('/'));
  const current = fs.existsSync(dest) ? fs.readFileSync(dest) : null;
  if (current && current.equals(content)) continue;
  problems.push(`${current ? 'differs' : 'missing'}: skills/contextanvil/${rel}`);
  if (!check) {
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, content);
  }
}
for (const rel of existing) {
  if (expected.has(rel)) continue;
  problems.push(`stale: skills/contextanvil/${rel}`);
  if (!check) fs.rmSync(path.join(skillDir, ...rel.split('/')));
}

if (check && problems.length) {
  process.stderr.write(`Skill engine is out of date:\n${problems.map((p) => `  ${p}`).join('\n')}\nRun: npm run skill:sync\n`);
  process.exit(1);
}
process.stdout.write(check ? 'Skill engine is in sync with src/.\n' : `Skill engine synced (${problems.length} file(s) changed).\n`);
